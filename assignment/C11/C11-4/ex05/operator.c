#include "do_op.h"

int	ft_plus(int a, int b)
{
	return (a + b);
}

int	ft_minus(int a, int b)
{
	return (a - b);
}

int	ft_multiple(int a, int b)
{
	return (a * b);
}

int	ft_divide(int a, int b)
{
	return (a / b);
}

int	ft_mod(int a, int b)
{
	return (a % b);
}

void	get_argv(char *argv, char **arr)
{
	int	i;
	int	j;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			if (*argv >= '1' && *argv <= '4')
			{
				arr[i][j] = *argv;
				argv += 2;
			}
			else
			{
				print_error();
				return ;
			}
			j++;
		}
		i++;
	}
}
